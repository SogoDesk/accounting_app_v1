#!/usr/bin/env node
// Generates the two starting migrations for node-pg-migrate (workflow step 0.1):
//
//   database/migrations/pgm/0001_baseline.sql        full schema, from pg_dump
//   database/migrations/pgm/0002_seed_reference.sql  tenant #1 reference rows
//
// Run it ONCE against a database that has every legacy migration applied and
// on which the server has booted at least once (so every ensure*Schema table
// exists). It only reads from that database.
//
//   npm run migrate:baseline
//   npm run migrate:baseline -- --schema-only     regenerate 0001 only
//
// Needs pg_dump on PATH, or PG_DUMP=/path/to/pg_dump. Use the same major
// version as the server. Connection settings come from backend/.env
// (DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASSWORD).

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");
const { Client } = require("pg");

require("dotenv").config({ path: path.resolve(__dirname, "../.env") });

const OUT_DIR = path.resolve(__dirname, "../../database/migrations/pgm");
const SEED_TENANT_ID = 1;

// Reference rows a new database needs before the app can run. In Phase 2 this
// list becomes the tenant provisioning template (step 2.5).
const SEED_TABLES = [
  { table: "tenants", where: "id = $1" },
  { table: "roles", where: "tenant_id = $1" },
  { table: "role_permissions", where: "tenant_id = $1" },
  { table: "chart_of_accounts", where: "tenant_id = $1" },
  { table: "document_numbering_config", where: "tenant_id = $1" },
];

const pgEnv = {
  ...process.env,
  PGHOST: process.env.DB_HOST,
  PGPORT: process.env.DB_PORT || "5432",
  PGDATABASE: process.env.DB_NAME,
  PGUSER: process.env.DB_USER,
  PGPASSWORD: process.env.DB_PASSWORD,
};
// "no-verify" is a node-postgres value; libpq tools call it "require"
// (encrypted, certificate not verified).
if (pgEnv.PGSSLMODE === "no-verify") pgEnv.PGSSLMODE = "require";

function dumpSchema() {
  const pgDump = process.env.PG_DUMP || "pg_dump";
  const raw = execFileSync(
    pgDump,
    [
      "--schema-only",
      "--no-owner",
      "--no-privileges",
      "--no-comments",
      "--exclude-table=public.pgmigrations",
    ],
    { env: pgEnv, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
  );

  const body = raw
    .split(/\r?\n/)
    // psql-only meta-commands (pg_dump 17.6+/18) that the migration runner cannot execute
    .filter((line) => !/^\\(restrict|unrestrict)\b/.test(line))
    // the dump clears search_path for the session; objects are schema-qualified,
    // and leaving it empty would break the runner's own bookkeeping insert
    .filter((line) => !/^SELECT pg_catalog\.set_config\('search_path', '', false\);$/.test(line))
    .join("\n")
    .trim();

  const versionLine = (raw.match(/^-- Dumped from database version .*$/m) || [""])[0];

  return [
    "-- Up Migration",
    "-- =============================================================================",
    "-- 0001 baseline — full schema at the point node-pg-migrate was adopted.",
    "--",
    "-- Replaces database/migrations/legacy/*.sql and the boot-time ensure*Schema",
    "-- modules. Generated by backend/scripts/buildBaseline.js; do not edit by hand.",
    "-- Existing databases: mark as applied with  npm run migrate -- up --fake",
    `-- Source: ${process.env.DB_NAME} ${versionLine.replace(/^-- /, "")}`,
    "-- =============================================================================",
    "",
    body,
    "",
    "-- Down Migration",
    "-- The baseline is not reversible. Restore from backup instead.",
    "",
  ].join("\n");
}

async function dumpSeed() {
  const client = new Client({
    host: pgEnv.PGHOST,
    port: Number(pgEnv.PGPORT),
    database: pgEnv.PGDATABASE,
    user: pgEnv.PGUSER,
    password: pgEnv.PGPASSWORD,
    ssl: process.env.PGSSLMODE ? { rejectUnauthorized: false } : undefined,
  });
  await client.connect();

  const parts = [
    "-- Up Migration",
    "-- =============================================================================",
    "-- 0002 seed_reference — reference rows for tenant #1: the tenant itself, roles,",
    "-- role permissions, chart of accounts and document numbering.",
    "--",
    "-- Generated by backend/scripts/buildBaseline.js. Rows are inserted with",
    "-- ON CONFLICT DO NOTHING, so the migration is safe on a database that",
    "-- already holds them. Phase 2 (step 2.5) turns this into the tenant",
    "-- provisioning template.",
    "-- =============================================================================",
    "",
    "-- Row-level security is forced on tenant tables; inserts must carry the tenant.",
    `SELECT set_config('app.tenant_id', '${SEED_TENANT_ID}', true);`,
    "",
  ];

  try {
    await client.query("BEGIN READ ONLY");
    await client.query("SELECT set_config('app.tenant_id', $1, true)", [String(SEED_TENANT_ID)]);

    for (const { table, where } of SEED_TABLES) {
      // Generated columns cannot be inserted; identity ALWAYS columns need an override.
      const cols = await client.query(
        `SELECT column_name, is_identity, identity_generation
           FROM information_schema.columns
          WHERE table_schema = 'public' AND table_name = $1 AND is_generated = 'NEVER'
          ORDER BY ordinal_position`,
        [table]
      );
      const colList = cols.rows.map((c) => `"${c.column_name}"`).join(", ");
      const overriding = cols.rows.some((c) => c.identity_generation === "ALWAYS")
        ? " OVERRIDING SYSTEM VALUE"
        : "";

      const { rows } = await client.query(
        `SELECT coalesce(json_agg(t), '[]'::json) AS data
           FROM (SELECT * FROM public.${table} WHERE ${where} ORDER BY 1) t`,
        [SEED_TENANT_ID]
      );
      const json = JSON.stringify(rows[0].data);
      const count = rows[0].data.length;
      const tag = `$seed_${table}$`;

      parts.push(
        `-- ${table}: ${count} row(s)`,
        `INSERT INTO public.${table} (${colList})${overriding}`,
        `SELECT ${colList} FROM json_populate_recordset(NULL::public.${table}, ${tag}${json}${tag}::json)`,
        "ON CONFLICT DO NOTHING;",
        ""
      );

      // Keep serial sequences ahead of the seeded ids.
      const hasId = cols.rows.some((c) => c.column_name === "id");
      const seq = hasId
        ? await client.query("SELECT pg_get_serial_sequence($1, 'id') AS seq", [`public.${table}`])
        : { rows: [{}] };
      if (seq.rows[0] && seq.rows[0].seq) {
        parts.push(
          `SELECT setval('${seq.rows[0].seq}', GREATEST((SELECT coalesce(MAX(id), 0) FROM public.${table}), 1));`,
          ""
        );
      }
      console.log(`  ${table}: ${count} row(s)`);
    }
    await client.query("COMMIT");
  } finally {
    await client.end();
  }

  parts.push(
    "-- Down Migration",
    "-- Reference rows are not removed automatically; other data depends on them.",
    ""
  );
  return parts.join("\n");
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  console.log(`Reading schema from ${pgEnv.PGDATABASE} on ${pgEnv.PGHOST} ...`);
  fs.writeFileSync(path.join(OUT_DIR, "0001_baseline.sql"), dumpSchema());
  console.log("Wrote 0001_baseline.sql");

  if (!process.argv.includes("--schema-only")) {
    console.log("Reading reference rows ...");
    fs.writeFileSync(path.join(OUT_DIR, "0002_seed_reference.sql"), await dumpSeed());
    console.log("Wrote 0002_seed_reference.sql");
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
